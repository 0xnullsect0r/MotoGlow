#!/usr/bin/env python3
"""Write cad/pcb_data.scad from the real board and mech.py.

The enclosure used to carry its own hand-typed copy of the board's size and
mounting-hole positions. They drifted, and the case was built for a board that
no longer existed. Now there is one source and the case reads it.
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pcbnew, mech, gen_board

HERE = os.path.dirname(os.path.abspath(__file__))
OUT  = os.path.join(HERE, "..", "..", "cad", "pcb_data.scad")

b = gen_board.build()
holes = sorted((round(pcbnew.ToMM(fp.GetPosition().x), 3),
                round(pcbnew.ToMM(fp.GetPosition().y), 3))
               for fp in b.GetFootprints() if fp.GetReference().startswith("H"))

L = [
 "// GENERATED by hardware/motoglow-pcb/export_pcb_data.py -- do not edit.",
 "// Regenerate after any change to the board or to mech.py, then re-run",
 "// hardware/motoglow-pcb/verify_fit.py before printing anything.",
 "",
 f"pcb_x        = {mech.BOARD_W};",
 f"pcb_y        = {mech.BOARD_H};",
 f"pcb_t        = {mech.PCB_T};",
 f"pcb_standoff = {mech.STANDOFF};",
 "// Mounting holes in BOARD coordinates, origin at the board's bottom-left.",
 "pcb_holes    = [" + ", ".join(f"[{x},{y}]" for x, y in holes) + "];",
 "",
 f"case_margin  = {mech.MARGIN};     // board edge to the inside face of the wall",
 f"case_floor_t = {mech.FLOOR_T};",
 f"case_inner_h = {round(mech.interior_h(), 2)};",
 f"port_z       = {round(mech.port_centre_z(), 2)};   // above the inside floor",
 "",
 "// [face, position along that face in board coords, hole dia, flange dia, label]",
 "// face: \"W\" = board x=0 wall, \"E\" = x=pcb_x, \"N\" = y=0, \"S\" = y=pcb_y",
 "ports = [",
]
for face, at, kind, name in mech.PORTS:
    L.append(f'  ["{face}", {at}, {mech.HOLE_D[kind]}, {2*mech.FLANGE_R[kind]}, "{name}"],')
L += ["];", ""]
open(OUT, "w").write("\n".join(L) + "\n")
print("wrote", os.path.normpath(OUT))
